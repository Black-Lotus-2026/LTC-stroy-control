"""Generate R1 TypeScript and runtime decoders from the same schemas as OpenAPI.

Run with backend/.venv/bin/python scripts/generate_customer_contract.py [--check].
No application configuration, database, provider or network is loaded.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from pydantic import BaseModel, TypeAdapter

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.schemas import customer_control as contracts  # noqa: E402
from app.schemas import live_demo as live_contracts  # noqa: E402
from app.schemas.recording_analysis import PlaybackSessionDTO  # noqa: E402


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf", "allOf"):
        if key in schema:
            return (
                "("
                + (" & " if key == "allOf" else " | ").join(ts(s) for s in schema[key])
                + ")"
            )
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind in {"integer", "number"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        return f'Array<{ts(schema.get("items", {}))}>'
    if kind == "object" or "properties" in schema:
        if "properties" not in schema:
            return f'Record<string, {ts(schema.get("additionalProperties", {}))}>'
        required = schema.get("required", [])
        if not schema["properties"]:
            return "Record<string, never>"
        return (
            "{\n"
            + "\n".join(
                f'  {json.dumps(k)}{"" if k in required else "?"}: {ts(v)};'
                for k, v in schema["properties"].items()
            )
            + "\n}"
        )
    return "unknown"


def main():
    schemas = {}
    for module in (contracts, live_contracts):
        for name, value in vars(module).items():
            if (
                isinstance(value, type)
                and issubclass(value, BaseModel)
                and value.__module__ == module.__name__
            ):
                schema = value.model_json_schema(ref_template="#/$defs/{model}")
                schemas.update(schema.pop("$defs", {}))
                schemas[name] = schema
    for name in ("IncidentDTO", "IncidentCommandDTO", "AccessScope", "Permission"):
        schema = TypeAdapter(getattr(contracts, name)).json_schema(
            ref_template="#/$defs/{model}"
        )
        schemas.update(schema.pop("$defs", {}))
        schemas[name] = schema
    schemas["PlaybackSessionDTO"] = PlaybackSessionDTO.model_json_schema()
    content = "// Generated by scripts/generate_customer_contract.py. Do not edit.\n"
    content += "\n".join(
        f"export type {name} = {ts(schema)};\n"
        for name, schema in sorted(schemas.items())
    )
    content += (
        "\nexport interface CustomerControlContracts {\n"
        + "\n".join(f"  {name}: {name};" for name in sorted(schemas))
        + "\n}\n"
    )
    content += """
interface Schema {
  $ref?: string; type?: string; const?: unknown; enum?: unknown[];
  anyOf?: Schema[]; oneOf?: Schema[]; allOf?: Schema[];
  properties?: Record<string, Schema>; required?: string[];
  items?: Schema; additionalProperties?: boolean | Schema;
  minimum?: number; maximum?: number; minLength?: number; maxLength?: number;
  minItems?: number; maxItems?: number; pattern?: string; format?: string;
}
"""

    # Metadata unsupported by the small validator is intentionally discarded.
    def runtime(s):
        allowed = {
            "$ref",
            "type",
            "const",
            "enum",
            "anyOf",
            "oneOf",
            "allOf",
            "properties",
            "required",
            "items",
            "additionalProperties",
            "minimum",
            "maximum",
            "minLength",
            "maxLength",
            "minItems",
            "maxItems",
            "pattern",
            "format",
        }
        return {
            k: (
                {a: runtime(b) for a, b in v.items()}
                if k == "properties"
                else runtime(v)
                if isinstance(v, dict)
                else [runtime(a) if isinstance(a, dict) else a for a in v]
                if isinstance(v, list)
                else v
            )
            for k, v in s.items()
            if k in allowed
        }

    content += (
        "const schemas: Record<string, Schema> = "
        + json.dumps(
            {k: runtime(v) for k, v in schemas.items()},
            ensure_ascii=False,
            separators=(",", ":"),
        )
        + ";\n"
    )
    content += """
function matches(s: Schema, value: unknown): boolean {
  if (s.$ref) return matches(schemas[s.$ref.split('/').pop() ?? ''], value);
  if ('const' in s && value !== s.const) return false;
  if (s.enum && !s.enum.includes(value)) return false;
  if (s.anyOf && !s.anyOf.some(x => matches(x, value))) return false;
  if (s.oneOf && !s.oneOf.some(x => matches(x, value))) return false;
  if (s.allOf && !s.allOf.every(x => matches(x, value))) return false;
  if (s.type === 'null') return value === null;
  if (s.type === 'boolean' && typeof value !== 'boolean') return false;
  if (s.type === 'string') {
    if (typeof value !== 'string') return false;
    if (s.minLength !== undefined && value.length < s.minLength) return false;
    if (s.maxLength !== undefined && value.length > s.maxLength) return false;
    if (s.pattern && !new RegExp(s.pattern).test(value)) return false;
    const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
    if (s.format === 'uuid' && !uuid.test(value)) return false;
    if (s.format === 'date-time') {
      if (!/(Z|[+-]\\d\\d:\\d\\d)$/.test(value)) return false;
      if (Number.isNaN(Date.parse(value))) return false;
    }
  }
  if (s.type === 'number' || s.type === 'integer') {
    if (typeof value !== 'number' || !Number.isFinite(value)) return false;
    if (s.type === 'integer' && !Number.isInteger(value)) return false;
    if (s.minimum !== undefined && value < s.minimum) return false;
    if (s.maximum !== undefined && value > s.maximum) return false;
  }
  if (s.type === 'array') {
    if (!Array.isArray(value)) return false;
    if (s.minItems !== undefined && value.length < s.minItems) return false;
    if (s.maxItems !== undefined && value.length > s.maxItems) return false;
    if (s.items && !value.every(x => matches(s.items ?? {}, x))) return false;
  }
  if (s.type === 'object' || s.properties) {
    if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
    const row = value as Record<string, unknown>;
    if (s.required?.some(k => !(k in row))) return false;
    for (const [key, val] of Object.entries(row)) {
      const property = s.properties?.[key];
      if (property && !matches(property, val)) return false;
      if (!property && s.additionalProperties === false) return false;
      if (!property && typeof s.additionalProperties === 'object') {
        if (!matches(s.additionalProperties, val)) return false;
      }
    }
  }
  return true;
}
export function decodeCustomerControl<K extends keyof CustomerControlContracts>(
  name: K, value: unknown,
): CustomerControlContracts[K] {
  if (!matches(schemas[name], value)) throw new Error(`Неверный ответ API: ${name}`);
  return value as CustomerControlContracts[K];
}
"""
    path = ROOT / "src/api/generated/customerControl.ts"
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("Generated customerControl.ts differs; regenerate")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


if __name__ == "__main__":
    main()
